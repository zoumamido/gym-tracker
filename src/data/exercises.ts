import type { Equipment, Exercise, EquipmentAccess } from '../lib/types';

type Def = Omit<Exercise, 'id' | 'kind' | 'met' | 'lowerBody' | 'secondary' | 'tips'> &
  Partial<Pick<Exercise, 'kind' | 'met' | 'lowerBody' | 'secondary' | 'tips'>>;

const LOWER = new Set(['quads', 'hamstrings', 'glutes', 'calves']);

function make(id: string, d: Def): Exercise {
  return {
    id,
    kind: 'strength',
    met: d.category === 'compound' ? 6 : 3.5,
    lowerBody: d.primary.some((m) => LOWER.has(m)),
    secondary: [],
    tips: [],
    ...d,
  };
}

